#!/usr/bin/env python3
"""Create a minimal tarball for transferring a MARS dataset run.

Run this on MARS inside or near a completed `sample-dataset` run. By default it
packages lightweight validation-critical artifacts: manifest, rows CSV,
per-evaluation summary, Touchstone, command, layout JSON files, raw clearance
audit JSON when present, and quality-gate/progress evidence. Optional flags can
add GDS and preview images when local geometry/clearance re-audit is needed.
Generated bytecode/cache and platform metadata files are always excluded.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import tarfile
from datetime import datetime
from pathlib import Path


INCLUDE_PATTERNS = (
    "dataset_manifest.json",
    "dataset_rows.csv",
    "final_s8p_physical_feature_500*.yaml",
    "final_s8p_physical_feature_500*.yml",
    "validation_report*.md",
    "validation_summary*.json",
    "frequency_backfill_summary.json",
    "final500_ground_clearance_audit.json",
    "evaluations/*/summary.json",
    "evaluations/*/emx/*.s*p",
    "evaluations/*/emx/emx_command.json",
    "evaluations/*/layout/*.json",
    "evaluations/*/*.layout.json",
    "dataset_quality_gates*/**/*summary*.json",
    "dataset_quality_gates*/**/*report*.md",
    "dataset_quality_gates*/**/*.csv",
    "mars_run_progress_audit*/**/*summary*.json",
    "mars_run_progress_audit*/**/*report*.md",
    "mars_run_progress_audit*/**/*.csv",
    "mars_run_progress_watch*/**/*.json",
    "mars_run_progress_watch*/**/*.jsonl",
    "mars_run_progress_watch*/**/*.md",
    "mars_run_progress_watch*/**/*.csv",
    "next_gen_s8p_mars_run_status*/**/*summary*.json",
    "next_gen_s8p_mars_run_status*/**/*report*.md",
    "next_gen_s8p_mars_run_status*/**/*.csv",
    "next_gen_s8p_objective_acceptance*/**/*summary*.json",
    "next_gen_s8p_objective_acceptance*/**/*AUDIT*.md",
    "next_gen_s8p_objective_acceptance*/**/*.csv",
)

GDS_PATTERNS = (
    "evaluations/*/layout/*.gds",
    "evaluations/*/*.gds",
)

LAYOUT_PREVIEW_PATTERNS = (
    "evaluations/*/layout/*.png",
    "evaluations/*/layout/*.svg",
    "evaluations/*/*.png",
    "evaluations/*/*.svg",
)

QUALITY_FIGURE_PATTERNS = (
    "dataset_quality_gates*/**/*.png",
    "dataset_quality_gates*/**/*.svg",
)

HFSS_VALIDATION_ASSET_PATTERNS = (
    "dataset_quality_gates*/selected_s8p_hfss_handoff/**/*",
    "dataset_quality_gates*/selected_s8p_hfss_aedt_scripts/**/*",
    "dataset_quality_gates*/selected_s8p_hfss_payload_views/**/*",
    "dataset_quality_gates*/selected_s8p_hfss_postrun_validation/**/*",
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", help="Completed dataset run directory")
    parser.add_argument("--out", default=None, help="Output .tar.gz path")
    parser.add_argument("--inventory", default=None, help="Output inventory JSON path")
    parser.add_argument("--report", default=None, help="Output human-readable inventory Markdown report path")
    parser.add_argument("--include-gds", action="store_true", help="Include layout GDS files for local geometry/clearance re-audit")
    parser.add_argument(
        "--include-layout-previews",
        action="store_true",
        help="Include layout preview/debug images when present",
    )
    parser.add_argument(
        "--include-quality-figures",
        action="store_true",
        help="Include PNG/SVG figures produced by dataset quality gates",
    )
    parser.add_argument(
        "--include-hfss-validation-assets",
        action="store_true",
        help="Include selected-sample HFSS handoff/AEDT/payload/postrun assets from dataset_quality_gates*",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    run_dir = Path(args.run_dir).expanduser().resolve()
    if not run_dir.is_dir():
        raise SystemExit(f"Run directory does not exist: {run_dir}")
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    out_path = Path(args.out).expanduser().resolve() if args.out else run_dir.parent / f"{run_dir.name}_minimal_{timestamp}.tar.gz"
    inventory_path = Path(args.inventory).expanduser().resolve() if args.inventory else out_path.with_suffix(out_path.suffix + ".inventory.json")
    report_path = Path(args.report).expanduser().resolve() if args.report else out_path.with_suffix(out_path.suffix + ".inventory.md")
    patterns = _patterns_for_args(args)
    files = _collect_files(run_dir, patterns)
    if not files:
        raise SystemExit(f"No files matched transfer patterns in {run_dir}")
    empty_files = _empty_transfer_files(files)
    if empty_files:
        preview = "\n".join(
            f"- {path.relative_to(run_dir)}"
            for path in empty_files[:20]
        )
        extra = "" if len(empty_files) <= 20 else f"\n... and {len(empty_files) - 20} more"
        raise SystemExit(
            "Refusing to package empty transfer files; rerun or repair MARS outputs before transfer:\n"
            f"{preview}{extra}"
        )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(out_path, "w:gz") as tar:
        for path in files:
            tar.add(path, arcname=str(path.relative_to(run_dir.parent)))
    sha256 = _sha256(out_path)
    inventory = {
        "run_dir": str(run_dir),
        "tarball": str(out_path),
        "report": str(report_path),
        "tarball_sha256": sha256,
        "file_count": len(files),
        "include_gds": bool(args.include_gds),
        "include_layout_previews": bool(args.include_layout_previews),
        "include_quality_figures": bool(args.include_quality_figures),
        "include_hfss_validation_assets": bool(args.include_hfss_validation_assets),
        "patterns": list(patterns),
        "empty_file_count": 0,
        "category_counts": _category_counts(run_dir, files),
        "files": [
            {
                "path": str(path),
                "relative_to_run_parent": str(path.relative_to(run_dir.parent)),
                "size_bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
            for path in files
        ],
    }
    inventory_path.write_text(json.dumps(inventory, indent=2), encoding="utf-8")
    report_path.write_text(_render_inventory_report(inventory), encoding="utf-8")
    sha_path = out_path.with_suffix(out_path.suffix + ".sha256")
    sha_path.write_text(f"{sha256}  {out_path.name}\n", encoding="utf-8")
    print(f"tarball={out_path}")
    print(f"sha256={sha256}")
    print(f"sha256_file={sha_path}")
    print(f"inventory={inventory_path}")
    print(f"report={report_path}")
    print(f"file_count={len(files)}")
    return 0


def _patterns_for_args(args: argparse.Namespace) -> tuple[str, ...]:
    patterns = list(INCLUDE_PATTERNS)
    if args.include_gds:
        patterns.extend(GDS_PATTERNS)
    if args.include_layout_previews:
        patterns.extend(LAYOUT_PREVIEW_PATTERNS)
    if args.include_quality_figures:
        patterns.extend(QUALITY_FIGURE_PATTERNS)
    if args.include_hfss_validation_assets:
        patterns.extend(HFSS_VALIDATION_ASSET_PATTERNS)
    return tuple(patterns)


def _collect_files(run_dir: Path, patterns: tuple[str, ...] = INCLUDE_PATTERNS) -> list[Path]:
    files: set[Path] = set()
    for pattern in patterns:
        files.update(
            path
            for path in run_dir.glob(pattern)
            if path.is_file() and not _is_excluded_transfer_path(path.relative_to(run_dir))
        )
    return sorted(files)


def _empty_transfer_files(files: list[Path]) -> list[Path]:
    return [path for path in files if path.stat().st_size <= 0]


def _is_excluded_transfer_path(rel_path: Path) -> bool:
    parts = rel_path.as_posix().split("/")
    return any(
        part == "__pycache__" or part == ".DS_Store" or part.startswith("._")
        for part in parts
    ) or rel_path.suffix in {".pyc", ".pyo"}


def _category_counts(run_dir: Path, files: list[Path]) -> dict[str, int]:
    counts = {
        "dataset_manifest": 0,
        "dataset_rows": 0,
        "run_config_files": 0,
        "evaluation_summaries": 0,
        "touchstone_files": 0,
        "emx_command_files": 0,
        "layout_json_files": 0,
        "clearance_audit_files": 0,
        "gds_files": 0,
        "layout_preview_files": 0,
        "quality_gate_top_summaries": 0,
        "quality_gate_summary_files": 0,
        "quality_gate_report_files": 0,
        "quality_gate_csv_files": 0,
        "quality_gate_figure_files": 0,
        "progress_audit_summary_files": 0,
        "progress_audit_report_files": 0,
        "progress_audit_csv_files": 0,
        "progress_watch_summary_files": 0,
        "progress_watch_history_files": 0,
        "progress_watch_snapshot_files": 0,
        "next_gen_run_status_summary_files": 0,
        "next_gen_run_status_report_files": 0,
        "next_gen_run_status_csv_files": 0,
        "objective_acceptance_summary_files": 0,
        "objective_acceptance_report_files": 0,
        "objective_acceptance_csv_files": 0,
        "hfss_validation_asset_files": 0,
        "hfss_validation_touchstone_files": 0,
        "hfss_validation_script_files": 0,
    }
    for path in files:
        rel = path.relative_to(run_dir)
        rel_text = rel.as_posix()
        quality_gate_file = bool(rel.parts and rel.parts[0].startswith("dataset_quality_gates"))
        progress_audit_file = bool(rel.parts and rel.parts[0].startswith("mars_run_progress_audit"))
        progress_watch_file = bool(rel.parts and rel.parts[0].startswith("mars_run_progress_watch"))
        next_gen_status_file = any(part.startswith("next_gen_s8p_mars_run_status") for part in rel.parts)
        objective_acceptance_file = any(part.startswith("next_gen_s8p_objective_acceptance") for part in rel.parts)
        hfss_validation_asset_file = _is_hfss_validation_asset(rel)
        if rel_text == "dataset_manifest.json":
            counts["dataset_manifest"] += 1
        if rel_text == "dataset_rows.csv":
            counts["dataset_rows"] += 1
        if rel_text.startswith("final_s8p_physical_feature_500") and rel.suffix.lower() in {".yaml", ".yml"}:
            counts["run_config_files"] += 1
        if rel.match("evaluations/*/summary.json"):
            counts["evaluation_summaries"] += 1
        if rel.match("evaluations/*/emx/*.s*p"):
            counts["touchstone_files"] += 1
        if rel.match("evaluations/*/emx/emx_command.json"):
            counts["emx_command_files"] += 1
        if rel.match("evaluations/*/layout/*.json") or rel.match("evaluations/*/*.layout.json"):
            counts["layout_json_files"] += 1
        if rel_text == "final500_ground_clearance_audit.json":
            counts["clearance_audit_files"] += 1
        if rel.match("evaluations/*/layout/*.gds") or rel.match("evaluations/*/*.gds"):
            counts["gds_files"] += 1
        if (
            rel.match("evaluations/*/layout/*.png")
            or rel.match("evaluations/*/layout/*.svg")
            or rel.match("evaluations/*/*.png")
            or rel.match("evaluations/*/*.svg")
        ):
            counts["layout_preview_files"] += 1
        if quality_gate_file and rel.match("dataset_quality_gates*/dataset_quality_gates_summary.json"):
            counts["quality_gate_top_summaries"] += 1
        if quality_gate_file and path.suffix == ".json" and "summary" in path.name:
            counts["quality_gate_summary_files"] += 1
        if quality_gate_file and path.suffix == ".md" and "report" in path.name:
            counts["quality_gate_report_files"] += 1
        if quality_gate_file and path.suffix == ".csv":
            counts["quality_gate_csv_files"] += 1
        if quality_gate_file and path.suffix.lower() in {".png", ".svg"}:
            counts["quality_gate_figure_files"] += 1
        if progress_audit_file and rel.name == "mars_run_progress_summary.json":
            counts["progress_audit_summary_files"] += 1
        if progress_audit_file and rel.name == "mars_run_progress_report.md":
            counts["progress_audit_report_files"] += 1
        if progress_audit_file and rel.suffix == ".csv":
            counts["progress_audit_csv_files"] += 1
        if progress_watch_file and rel.name == "mars_run_progress_watch_summary.json":
            counts["progress_watch_summary_files"] += 1
        if progress_watch_file and rel.name in {"mars_run_progress_watch_history.csv", "mars_run_progress_watch_history.jsonl"}:
            counts["progress_watch_history_files"] += 1
        if progress_watch_file and "snapshots" in rel.parts:
            counts["progress_watch_snapshot_files"] += 1
        if next_gen_status_file and rel.name == "next_gen_s8p_mars_run_status_summary.json":
            counts["next_gen_run_status_summary_files"] += 1
        if next_gen_status_file and rel.suffix == ".md" and "report" in rel.name:
            counts["next_gen_run_status_report_files"] += 1
        if next_gen_status_file and rel.suffix == ".csv":
            counts["next_gen_run_status_csv_files"] += 1
        if objective_acceptance_file and rel.name == "next_gen_s8p_objective_acceptance_summary.json":
            counts["objective_acceptance_summary_files"] += 1
        if objective_acceptance_file and rel.suffix == ".md":
            counts["objective_acceptance_report_files"] += 1
        if objective_acceptance_file and rel.suffix == ".csv":
            counts["objective_acceptance_csv_files"] += 1
        if hfss_validation_asset_file:
            counts["hfss_validation_asset_files"] += 1
        if hfss_validation_asset_file and rel.suffix.lower() in {".s8p", ".s4p"}:
            counts["hfss_validation_touchstone_files"] += 1
        if hfss_validation_asset_file and rel.suffix.lower() in {".py", ".ps1", ".sh"}:
            counts["hfss_validation_script_files"] += 1
    return counts


def _is_hfss_validation_asset(rel: Path) -> bool:
    parts = rel.parts
    if not parts or not parts[0].startswith("dataset_quality_gates"):
        return False
    return any(
        part
        in {
            "selected_s8p_hfss_handoff",
            "selected_s8p_hfss_aedt_scripts",
            "selected_s8p_hfss_payload_views",
            "selected_s8p_hfss_postrun_validation",
        }
        for part in parts
    )


def _render_inventory_report(inventory: dict[str, object]) -> str:
    category_counts = inventory.get("category_counts")
    lines = [
        "# MARS Dataset Transfer Inventory",
        "",
        f"- Run directory: `{inventory.get('run_dir')}`",
        f"- Tarball: `{inventory.get('tarball')}`",
        f"- Tarball SHA256: `{inventory.get('tarball_sha256')}`",
        f"- File count: `{inventory.get('file_count')}`",
        f"- Empty files: `{inventory.get('empty_file_count')}`",
        f"- Include GDS: `{inventory.get('include_gds')}`",
        f"- Include layout previews: `{inventory.get('include_layout_previews')}`",
        f"- Include quality figures: `{inventory.get('include_quality_figures')}`",
        f"- Include HFSS validation assets: `{inventory.get('include_hfss_validation_assets')}`",
        "",
        "## Category Counts",
        "",
        "| Category | Count |",
        "| --- | ---: |",
    ]
    if isinstance(category_counts, dict):
        for key in sorted(category_counts):
            lines.append(f"| `{key}` | {category_counts[key]} |")
    else:
        lines.append("| `category_counts_missing` | 0 |")
    patterns = inventory.get("patterns")
    if isinstance(patterns, list):
        lines.extend(["", "## Included Patterns", ""])
        for pattern in patterns:
            lines.append(f"- `{pattern}`")
    lines.extend(
        [
            "",
            "## Boundaries",
            "",
            "- This report proves transfer package composition and hashes only.",
            "- Empty transfer files are refused before tarball creation.",
            "- Python bytecode/cache and platform metadata files are excluded from transfer packages.",
            "- It does not prove EMX/HFSS/ADS agreement, Zin coverage, or model training readiness.",
            "- Verify the tarball with `verify_mars_dataset_package.py` before trusting or unpacking it.",
        ]
    )
    return "\n".join(lines) + "\n"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


if __name__ == "__main__":
    raise SystemExit(main())
